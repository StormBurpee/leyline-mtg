import Ajv2020 from 'ajv/dist/2020.js';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { format, resolveConfig } from 'prettier';
import { compilePack } from '../packages/cards/pack.js';
import { canonical } from '../packages/cards/compiler.js';
const root = new URL('../packages/cards/', import.meta.url),
  check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check'))
  throw new Error('Usage: node scripts/compile-card-pack.mjs [--check]');
const manifest = JSON.parse(await readFile(new URL('pack.json', root), 'utf8'));
if (manifest.format !== 'leyline-card-pack' || manifest.schemaVersion !== 1)
  throw new Error('Unsupported pack format.');
const mechanics = JSON.parse(await readFile(new URL('mechanics.json', root), 'utf8'));
const schema = JSON.parse(await readFile(new URL('schema/card.schema.json', root), 'utf8'));
const validate = new Ajv2020({ allErrors: true, strict: true }).compile(schema);
const cards = [];
for (const entry of (await readdir(new URL('cards/', root), { withFileTypes: true })).sort((a, b) =>
  a.name.localeCompare(b.name, 'en'),
)) {
  if (entry.isSymbolicLink()) throw new Error('Card source symlinks are not accepted.');
  if (!entry.isFile() || !entry.name.endsWith('.json')) continue;
  const body = await readFile(new URL(`cards/${entry.name}`, root), 'utf8');
  if (Buffer.byteLength(body) > 512000) throw new Error(`${entry.name}: source file is too large.`);
  const card = JSON.parse(body);
  if (!validate(card)) throw new Error(`${entry.name}: ${JSON.stringify(validate.errors)}`);
  cards.push(card);
}
const result = compilePack(cards, { mechanics });
if (!result.ok)
  throw new Error(result.diagnostics.map((d) => `${d.code} ${d.path}: ${d.message}`).join('\n'));
const sourceHash = createHash('sha256')
  .update(JSON.stringify(canonical({ manifest, mechanics, cards })))
  .digest('hex');
const config = await resolveConfig(new URL('../.prettierrc.json', import.meta.url).pathname);
const moduleText = await format(
  `/** Generated by npm run cards:build. Edit packages/cards/cards/*.json instead. */\nexport const definitions = ${JSON.stringify(result.definitions)};\nexport const cardIds = ${JSON.stringify(result.index)};\nexport const packIdentity = ${JSON.stringify({ id: manifest.id, version: manifest.version, schemaVersion: manifest.schemaVersion, sourceHash })};\n`,
  { ...config, parser: 'babel' },
);
const report = {
  ...manifest,
  sourceHash,
  cards: result.definitions.filter((d) => !d.token).length,
  tokens: result.definitions.filter((d) => d.token).length,
  identities: result.index,
};
const reportText = await format(JSON.stringify(report), { ...config, parser: 'json' });
for (const [url, body] of [
  [new URL('../packages/engine/src/generated-catalog.js', import.meta.url), moduleText],
  [new URL('compiled-manifest.json', root), reportText],
]) {
  if (check) {
    if ((await readFile(url, 'utf8')) !== body)
      throw new Error(`${url.pathname}: generated card data is stale. Run npm run cards:build.`);
  } else await writeFile(url, body);
}
console.log(
  `${check ? 'Verified' : 'Compiled'} ${report.cards} cards and ${report.tokens} tokens; source ${sourceHash.slice(0, 12)}.`,
);
